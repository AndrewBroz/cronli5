// Traditional Chinese paradigms for the options. Each row names the parts
// of its sentence in written order (`parts`), and `defaultParts` gives the
// same parts as the default style (Taiwan's) says them. An option may
// change the words of a part. It may not add, drop or reorder parts.
//
// Written by hand from src/lang/zh-hant/answers.md section 1.2.

const EVEN_BUT_8 = '0 0,2,4,6,10,12,14,16,18,20,22 * * *';

